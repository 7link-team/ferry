/** Adapt the upstream DTCG source; never edit tokens.generated.css by hand. */
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../src/shared/theme/raft/", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens.json", root), "utf8"));
const modes = { light: [], dark: [], desktop: [] };
const variable = path => `--raft-${path.join("-")}`;
function value(input) {
  if (Array.isArray(input) && input.length === 4) return `cubic-bezier(${input.join(", ")})`;
  if (typeof input === "number") return String(input);
  if (typeof input === "string") return input.replace(/\{([^}]+)\}/g, (_, name) => `var(${variable(name.split(".").filter(part => part !== "$root"))})`).replace(/var\(--(?!raft-)/g, "var(--raft-");
  if (input.colorSpace === "oklch") return `oklch(${input.components.join(" ")}${input.alpha !== undefined ? ` / ${input.alpha}` : ""})`;
  if ("value" in input && "unit" in input) return `${input.value}${input.unit}`;
  throw new Error(`Unsupported upstream token: ${JSON.stringify(input)}`);
}
function visit(node, path = []) {
  if ("$value" in node) {
    const extension = node.$extensions?.["build.botiverse.raft"] ?? {};
    modes.light.push(`  ${variable(path)}: ${value(node.$value)};`);
    if (extension.modes?.dark !== undefined) modes.dark.push(`  ${variable(path)}: ${value(extension.modes.dark)};`);
    if (extension.desktop !== undefined) modes.desktop.push(`  ${variable(path)}: ${value(extension.desktop)};`);
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key === "$root") visit(child, path);
    else if (!key.startsWith("$")) visit(child, [...path, key]);
  }
}
visit(tokens);
const selector = '[data-theme="neoBrutalism"]';
const css = `/* Generated by scripts/build-raft-theme.mjs from official Raft tokens.json.\n * Source: https://github.com/botiverse/raft-design/tree/1656b5a1c25add2ceda52c4e4d50aab99db27835\n * MIT: ./LICENSE. Do not edit this output; update the input and regenerate. */\n${selector} {\n${modes.light.join("\n")}\n}\n${selector}.dark {\n${modes.dark.join("\n")}\n}\n@media (width >= 48rem) and (pointer: fine) {\n${selector} {\n${modes.desktop.join("\n")}\n}\n}\n`;
const file = new URL("tokens.generated.css", root);
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== css) throw new Error("Raft generated tokens are stale. Run node scripts/build-raft-theme.mjs.");
} else writeFileSync(file, css);
