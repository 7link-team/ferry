/** Real browser + HTTP acceptance for the shared pipeline/template workspace. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, open, readFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:net';
import { parseDocument } from 'yaml';
import { chromium } from 'playwright';

const work = await mkdtemp(join(tmpdir(), 'template-editor-'));
const listener = createServer();
await new Promise(r => listener.listen(0, '127.0.0.1', r));
const port = listener.address().port;
await new Promise(r => listener.close(r));
const origin = `http://127.0.0.1:${port}`;
const log = await open(join(work, 'server.log'), 'w');
const env = { ...process.env, FERRY_DATA_DIR: work, FERRY_BIND: `127.0.0.1:${port}` };
delete env.FERRY_DATABASE_URL;
const server = spawn(resolve(process.env.FERRY_BINARY || 'target/debug/ferry-server'), [], { env, stdio: ['ignore', log.fd, log.fd], windowsHide: true });
let browser;
try {
  for (let i = 0; ; i++) {
    assert.equal(server.exitCode, null, 'server exited');
    try { if ((await fetch(`${origin}/api/status`)).ok) break; } catch {}
    assert(i < 200, 'server startup timed out');
    await new Promise(r => setTimeout(r, 100));
  }
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROME_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROME_PATH } : {}) });
  const context = await browser.newContext({ locale: 'zh-CN', viewport: { width: 1280, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const headers = { 'X-Ferry-Request': '1', 'Accept-Language': 'zh-CN' };
  const request = async (method, path, data) => {
    const response = await context.request.fetch(`${origin}/api${path}`, { method, headers, data });
    assert(response.ok(), `${method} ${path}: ${await response.text()}`);
    return response.status() === 204 ? undefined : response.json();
  };
  await request('POST', '/setup', { email: 'admin@example.invalid', name: 'Admin', password: 'temporary-admin-password', token: (await readFile(join(work, 'setup-token'), 'utf8')).trim() });
  const ws = (await request('POST', '/workspaces', { name: 'Template test', slug: 'template-test' })).id;
  const root = `/workspaces/${ws}`;
  const p = await context.newPage();
  const errors = [];
  p.on('pageerror', error => errors.push(error.stack || error.message));
  const canvas = () => p.locator('[aria-label="流水线画布"]');
  const name = 'YAML template';
  const setYaml = async (scope, value) => {
    await scope.locator('.monaco-editor .view-lines').click();
    await p.keyboard.press('ControlOrMeta+A');
    await p.evaluate(text => navigator.clipboard.writeText(text), value);
    await p.keyboard.press('ControlOrMeta+V');
  };
  const readYaml = async scope => {
    await scope.locator('.monaco-editor .view-lines').click();
    await p.keyboard.press('ControlOrMeta+A');
    await p.keyboard.press('ControlOrMeta+C');
    return p.evaluate(() => navigator.clipboard.readText());
  };
  const workflow = '# retain full workflow\nname: Advanced workflow\non: workflow_dispatch\npermissions:\n  contents: read\nconcurrency:\n  group: build-${{ github.ref }}\njobs:\n  build:\n    name: Build\n    runs-on: self-hosted\n    strategy:\n      matrix:\n        node: [20, 22]\n    services:\n      redis:\n        image: redis:7\n    steps:\n      - name: Setup Node\n        uses: actions/setup-node@v4\n        with:\n          node-version: "${{ matrix.node }}"\n      - run: echo done\n';
  await p.goto(`${origin}/zh-CN${root}/pipeline-templates/new`);
  await p.getByRole('tab', { name: '高级 YAML', exact: true }).click();
  await p.locator('.monaco-editor').waitFor();
  await p.getByRole('textbox', { name: '模板名称', exact: true }).fill(name);
  await p.getByRole('button', { name: '配置', exact: true }).click();
  assert.equal(await p.getByLabel('参数定义（JSON 数组）', { exact: false }).count(), 0);
  await p.getByRole('button', { name: '配置', exact: true }).click();
  await setYaml(p, workflow);
  await p.getByRole('button', { name: '变更对比', exact: true }).click();
  await p.locator('.monaco-diff-editor').waitFor();
  assert.equal(await p.locator('.monaco-diff-editor .editor').count(), 2);
  await p.getByRole('button', { name: '完整编辑', exact: true }).click();
  let full = p.getByRole('dialog');
  await full.locator('.monaco-diff-editor').waitFor();
  assert(await full.evaluate(element => element.getBoundingClientRect().height >= innerHeight - 2));
  assert.equal(await p.getByRole('button', { name: '保存并运行', exact: true }).count(), 0);
  await full.getByRole('button', { name: '退出完整编辑', exact: true }).click();
  await p.getByRole('button', { name: '变更对比', exact: true }).click();
  assert.equal(parseDocument(await readYaml(p)).toJS().jobs.build.steps[0].uses, 'actions/setup-node@v4');
  await p.getByRole('button', { name: '创建', exact: true }).click();
  await p.getByRole('cell', { name, exact: true }).waitFor();
  let row = (await request('GET', `${root}/pipeline-templates`)).items.find(row => row.name === name);
  assert(row);
  assert.equal(row.parameters, '[]');
  assert.equal(JSON.parse(row.content).workflow, workflow);
  console.log('PASS shared YAML creation, full-screen/diff draft retention, no template parameters or run button');
  const host = await request('POST', `${root}/nodes`, { name: 'Template host', connection: 'runner' });
  const envelope = JSON.parse(row.content);
  envelope.executor_bindings = [{ job_id: 'build', target_kind: 'host', target_ref: host.id, image: 'node:22' }];
  envelope.graph_layout = { build: { x: 80, y: 120 } };
  await request('PATCH', `${root}/pipeline-templates/${row.id}`, { ...row, content: JSON.stringify(envelope) });
  await p.goto(`${origin}/zh-CN${root}/pipeline-templates/${row.id}/edit`);
  await p.getByRole('tab', { name: '高级 YAML', exact: true }).click();
  await p.locator('.monaco-editor').waitFor();
  await p.getByRole('tab', { name: '可视化', exact: true }).click();
  await canvas().waitFor();
  await p.locator('.react-flow__node').getByRole('button', { name: /Setup Node/ }).click();
  assert.equal(await p.getByLabel('参数名', { exact: true }).count(), 0);
  await p.locator('summary').filter({hasText:'高级 YAML'}).evaluate(el=>{el.parentElement.open=true});
  await p.getByRole('button', { name: '步骤 YAML', exact: true }).click();
  const fragment = p.getByRole('dialog');
  await setYaml(fragment, '- invalid step shape\n');
  assert(await fragment.getByRole('button', { name: '应用到工作流', exact: true }).isDisabled());
  await fragment.getByRole('button', { name: '关闭，不应用', exact: true }).click();
  await p.locator('summary').filter({hasText:'高级 YAML'}).evaluate(el=>{el.parentElement.open=true});
  await p.getByRole('button', { name: '步骤 YAML', exact: true }).click();
  assert.match(await readYaml(fragment), /actions\/setup-node@v4/);
  await setYaml(fragment, 'name: Setup Node\nuses: actions/setup-node@v4\nwith:\n  node-version: "22"\n  cache: npm\nif: success()\nenv:\n  NODE_ENV: production\n');
  await fragment.getByRole('button', { name: '应用到工作流', exact: true }).click();
  await p.getByRole('tab', { name: '高级 YAML', exact: true }).click();
  const editedSource = await readYaml(p);
  const expected = parseDocument(workflow).toJS();
  expected.jobs.build.steps[0] = { name: 'Setup Node', uses: 'actions/setup-node@v4', with: { 'node-version': '22', cache: 'npm' }, if: 'success()', env: { NODE_ENV: 'production' } };
  assert.deepEqual(parseDocument(editedSource).toJS(), expected);
  assert.match(editedSource, /# retain full workflow/);
  await p.getByRole('button', { name: '变更对比', exact: true }).click();
  const diff = p.locator('.monaco-diff-editor');
  await diff.waitFor();
  const left = diff.locator('.editor.original .view-lines');
  await left.click(); await p.keyboard.press('ControlOrMeta+A'); await p.keyboard.press('ControlOrMeta+C');
  // Windows clipboard transport uses CRLF; the saved HTTP source is asserted byte-for-byte above.
  assert.equal((await p.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, '\n'), workflow, 'left is saved baseline');
  await p.getByRole('button', { name: '变更对比', exact: true }).click();
  await p.getByRole('button', { name: '保存', exact: true }).click();
  await p.getByRole('cell', { name, exact: true }).waitFor();
  row = await request('GET', `${root}/pipeline-templates/${row.id}`);
  const saved = JSON.parse(row.content);
  assert.deepEqual(parseDocument(saved.workflow).toJS(), expected);
  assert.deepEqual(saved.executor_bindings, envelope.executor_bindings);
  assert.deepEqual(saved.graph_layout, envelope.graph_layout);
  assert.deepEqual(saved.checkout_bindings, envelope.checkout_bindings);
  console.log('PASS step fragment validation/cancel/apply, full document and saved baseline preservation, HTTP persistence');
  await p.goto(`${origin}/zh-CN${root}/pipeline-templates/${row.id}`);
  await p.getByRole('tab', { name: '高级 YAML', exact: true }).click();
  await p.locator('.monaco-editor').waitFor();
  const before = await readYaml(p);
  await p.keyboard.type('must not alter readonly');
  assert.equal(await readYaml(p), before);
  const edit = p.getByRole('link', { name: '编辑', exact: true });
  const width = await edit.evaluate(element => { const footer = element.closest('[data-form-actions]'); const style = getComputedStyle(footer); return { actual: element.getBoundingClientRect().width, expected: footer.clientWidth - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight) }; });
  assert(Math.abs(width.actual - width.expected) < 2);
  assert.equal(await p.getByRole('button', { name: '保存', exact: true }).count(), 0);
  await mkdir('data/maintenance/template-editor', { recursive: true });
  await p.screenshot({ path: 'data/maintenance/template-editor/detail.png' });
  await p.setViewportSize({ width: 390, height: 844 });
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await p.screenshot({ path: 'data/maintenance/template-editor/mobile.png' });
  const rendered = await request('POST', `${root}/pipeline-templates/${row.id}/renderings`, { version: row.version, values: {} });
  assert.deepEqual(parseDocument(JSON.parse(rendered.definition).workflow).toJS(), expected);
  console.log('PASS readonly detail, full-width edit button, mobile layout, direct template rendering');
  assert.deepEqual(errors, []);
  console.log('PASS no browser errors');
} finally {
  if (browser) await browser.close();
  if (server.exitCode === null) { server.kill('SIGTERM'); await new Promise(r => server.once('exit', r)); }
  await log.close();
  await rm(work, { recursive: true, force: true });
}
