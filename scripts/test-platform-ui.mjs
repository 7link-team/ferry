/** Real Chromium acceptance for first-run initialization and platform management. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtemp, readFile, rm, open } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createServer } from 'node:net';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const work = await mkdtemp(join(tmpdir(), 'platform-ui-'));
const listener = createServer();
await new Promise(r => listener.listen(0, '127.0.0.1', r));
const port = listener.address().port;
await new Promise(r => listener.close(r));
const origin = `http://127.0.0.1:${port}`;
const log = await open(join(work, 'server.log'), 'w');
const env = { ...process.env, FERRY_DATA_DIR: work, FERRY_BIND: `127.0.0.1:${port}` };
delete env.FERRY_DATABASE_URL;
const server = spawn(resolve(process.env.FERRY_BINARY || 'target/debug/ferry-server'), [], { env, stdio: ['ignore', log.fd, log.fd], windowsHide: true });
let browser;
try {
  for (let i = 0; ; i++) {
    assert.equal(server.exitCode, null, 'server exited');
    try { if ((await fetch(`${origin}/api/status`)).ok) break; } catch {}
    assert(i < 200, 'server startup timed out');
    await new Promise(r => setTimeout(r, 100));
  }
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROME_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROME_PATH } : {}) });
  const context = await browser.newContext({ locale: 'zh-CN', extraHTTPHeaders: { 'Accept-Language': 'zh-CN' }, viewport: { width: 1280, height: 800 } });
  const page = await context.newPage();
  globalThis.failurePage = page;
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => requests.push(r.url()));
  await page.goto(origin);
  await page.getByRole('heading', { name: '初始化平台超级管理员' }).waitFor();
  assert.equal(await page.locator('input[name="token"]').count(), 1, 'web operator sees proof field');
  assert.equal(await page.getByText('还没有账号？注册').count(), 0, 'registration unavailable before setup');
  const token = (await readFile(join(work, 'setup-token'), 'utf8')).trim();
  // A full navigation simulates the native owned-sidecar handoff.
  await page.goto(`${origin}/?desktop=1#setup=${encodeURIComponent(token)}`);
  await page.getByRole('heading', { name: '初始化平台超级管理员' }).waitFor();
  assert.equal(await page.locator('input[name="token"]').count(), 0, 'native proof needs no manual input');
  assert.equal(new URL(page.url()).hash, '', 'proof immediately removed from history');
  await page.getByLabel('姓名', { exact: true }).fill('Platform Admin');
  await page.getByLabel('邮箱', { exact: true }).fill('admin@example.invalid');
  await page.getByLabel('密码', { exact: true }).fill('temporary-admin-password');
  await page.getByLabel('确认密码', { exact: true }).fill('temporary-wrong-password');
  await page.getByRole('button', { name: '初始化并进入平台' }).click();
  await page.getByText('两次输入的密码不一致。').waitFor();
  await page.getByLabel('确认密码', { exact: true }).fill('temporary-admin-password');
  const concurrent = await browser.newContext({ locale: 'zh-CN', extraHTTPHeaders: { 'Accept-Language': 'zh-CN' } });
  const concurrentPage = await concurrent.newPage();
  await concurrentPage.goto(`${origin}/#setup=${encodeURIComponent(token)}`);
  await concurrentPage.getByRole('heading', { name: '初始化平台超级管理员' }).waitFor();
  await concurrentPage.getByLabel('姓名', { exact: true }).fill('Concurrent');
  await concurrentPage.getByLabel('邮箱', { exact: true }).fill('concurrent@example.invalid');
  await concurrentPage.getByLabel('密码', { exact: true }).fill('temporary-concurrent-password');
  await concurrentPage.getByLabel('确认密码', { exact: true }).fill('temporary-concurrent-password');
  await page.getByRole('button', { name: '初始化并进入平台' }).click();
  await page.waitForURL('**/zh-CN/platform/workspaces');
  await concurrentPage.getByRole('button', { name: '初始化并进入平台' }).click();
  await concurrentPage.getByText('平台已初始化，请登录。').waitFor();
  await concurrentPage.getByRole('button', { name: '登录', exact: true }).waitFor();
  assert.equal(await concurrentPage.getByRole('button', { name: '初始化并进入平台' }).count(), 0, 'concurrent setup loser can immediately sign in');
  assert.equal(new URL(page.url()).pathname, '/zh-CN/platform/workspaces');
  await page.getByRole('button', { name: '创建工作空间', exact: true }).click();
  await page.getByRole('textbox', { name: '名称', exact: true }).fill('First workspace');
  await page.getByRole('textbox', { name: '标识', exact: true }).fill('first');
  await page.getByRole('button', { name: '创建', exact: true }).click();
  await page.getByRole('cell', { name: 'First workspace', exact: true }).waitFor();
  await page.getByRole('row').filter({ hasText: 'First workspace' }).getByRole('cell', { name: '拥有者（我创建的）', exact: true }).waitFor();
  await page.screenshot({ path: '/tmp/platform-workspaces.png', fullPage: true });
  // Shared table actions are links rendered in each row's actions menu.
  const row = page.getByRole('row').filter({ hasText: 'First workspace' });
  const detailsPath = new URL(await row.getByRole('link', { name: '查看', exact: true }).getAttribute('href'), origin).pathname;
  assert.match(detailsPath, /^\/zh-CN\/platform\/workspaces\/\d+$/, 'workspace exposes its existing detail route');
  for (const width of [1280, 900, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await row.getByRole('cell', { name: 'First workspace', exact: true }).click();
    const details = page.locator('form.resource-detail');
    await details.waitFor();
    await page.getByRole('heading', { name: 'First workspace', exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, detailsPath, 'row opens read-only details instead of editing');
    assert.equal(await details.getByRole('textbox').count(), 0, 'detail fields render as text');
    assert.equal(await details.locator('button[type="submit"]').count(), 0, 'viewing cannot submit changes');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `workspace details fit ${width}px`);
    await page.screenshot({ path: join(process.env.TEST_SCREENSHOT_DIR || work, `workspace-details-${width}.png`), fullPage: true });
    await page.reload();
    await page.locator('form.resource-detail').waitFor();
    await page.getByRole('link', { name: '编辑', exact: true }).click();
    await page.getByRole('textbox', { name: '名称', exact: true }).waitFor();
    assert.equal(new URL(page.url()).pathname, detailsPath + '/edit', 'editing has its own explicit route');
    await page.getByRole('link', { name: '取消', exact: true }).click();
    await row.getByRole('cell', { name: 'First workspace', exact: true }).waitFor();
  }
  await page.setViewportSize({ width: 1280, height: 800 });
  const enter = row.getByRole('link', { name: '进入工作空间', exact: true });
  if (!(await enter.isVisible())) await row.getByRole('button').last().click();
  const entryPath = new URL(await enter.getAttribute('href'), origin).pathname;
  assert.match(entryPath, /^\/zh-CN\/workspaces\/\d+\//, 'workspace entry uses its Snowflake ID');
  await page.getByRole('link', { name: '进入工作空间', exact: true }).click();
  await page.getByRole('button', { name: '平台管理', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, entryPath, 'new workspace can be entered without stale identity redirect');
  await page.getByRole('button', { name: '平台管理', exact: true }).click();
  await page.waitForURL('**/zh-CN/platform/workspaces');
  await page.getByRole('cell', { name: 'First workspace', exact: true }).waitFor();
  await page.getByRole('link', { name: '平台用户', exact: true }).click();
  await page.getByRole('cell', { name: 'admin@example.invalid', exact: true }).waitFor();
  await page.getByRole('row').filter({ hasText: 'admin@example.invalid' }).getByRole('link', { name: '编辑', exact: true }).click();
  await page.getByRole('switch').nth(1).click();
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('必须保留至少一个启用的平台超级管理员。').waitFor();
  const ordinary = await browser.newContext({ locale: 'zh-CN', extraHTTPHeaders: { 'Accept-Language': 'zh-CN' } });
  const registered = await ordinary.request.post(`${origin}/api/users`, { headers: { 'X-Ferry-Request': '1', 'Accept-Language': 'zh-CN' }, data: { name: 'Ordinary', email: 'ordinary@example.invalid', password: 'temporary-ordinary-password' } });
  assert(registered.ok());
  const ordinaryPage = await ordinary.newPage();
  await ordinaryPage.goto(`${origin}/_platform/users`);
  await ordinaryPage.getByText('当前账号没有平台管理权限。').waitFor();
  await ordinaryPage.goto(origin + detailsPath);
  await ordinaryPage.getByText('当前账号没有平台管理权限。').waitFor();
  assert.equal((await ordinary.request.get(`${origin}/api/platform/workspaces/${detailsPath.split('/').at(-1)}`)).status(), 403, 'ordinary users cannot read platform workspace details');
  assert.equal(await ordinaryPage.getByRole('cell').count(), 0, 'ordinary account cannot view platform table');
  await page.getByRole('link', { name: '平台设置', exact: true }).click();
  await page.getByRole('button', { name: '账号注册', exact: true }).click();
  const toggle = page.getByRole('switch', { name: '允许注册新账号', exact: true });
  await toggle.waitFor();
  assert.equal(await toggle.getAttribute('aria-checked'), 'true');
  await toggle.click();
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/platform/settings/1') && r.request().method() === 'GET'), page.getByRole('button', { name: '保存', exact: true }).click()]);
  assert.equal((await (await context.request.get(`${origin}/api/setup`)).json()).registration_enabled, false);
  await page.screenshot({ path: '/tmp/platform-settings.png', fullPage: true });
  // Own profile: reachable from platform management and from the workspace account menu.
  await page.getByRole('button', { name: /Platform Admin/ }).click();
  await page.getByRole('menuitem', { name: '个人资料', exact: true }).click();
  await page.getByRole('heading', { name: '个人资料', exact: true }).first().waitFor();
  assert.equal(new URL(page.url()).pathname, '/zh-CN/account');
  const nameField = page.getByLabel('姓名', { exact: true }), emailField = page.getByRole('textbox', { name: '登录邮箱', exact: true });
  const newPassword = page.getByLabel('新密码', { exact: true }), currentPassword = page.getByLabel('当前密码', { exact: true });
  // Profile fields are grouped: name under basics, email and passwords under security.
  const openGroup = async (label, field) => { await page.getByText(label, { exact: true }).first().click(); await field.waitFor(); };
  await nameField.waitFor();
  assert.equal(await nameField.inputValue(), 'Platform Admin');
  await openGroup('账号安全', emailField);
  assert.equal(await emailField.inputValue(), 'admin@example.invalid');
  assert.deepEqual([await newPassword.getAttribute('type'), await currentPassword.getAttribute('type'), await newPassword.inputValue()], ['password', 'password', '']);
  await openGroup('基础资料', nameField);
  await nameField.fill('Renamed Admin');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('个人资料已保存。').waitFor();
  assert.equal((await (await context.request.get(`${origin}/api/me`)).json()).user.name, 'Renamed Admin', 'name saved without a password');
  await openGroup('账号安全', emailField);
  await emailField.fill('renamed@example.invalid');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('当前密码不正确。修改邮箱或密码需要填写当前密码。').waitFor();
  await currentPassword.fill('temporary-admin-password');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await page.getByText('个人资料已保存。').last().waitFor();
  assert.equal((await (await context.request.get(`${origin}/api/me`)).json()).user.email, 'renamed@example.invalid', 'email changed with the current password; this session stays signed in');
  await openGroup('账号安全', emailField);
  await page.waitForFunction(() => document.querySelector('input[type="password"]')?.value === '');
  assert.equal(await emailField.inputValue(), 'renamed@example.invalid');
  assert.deepEqual([await newPassword.inputValue(), await currentPassword.inputValue()], ['', ''], 'saved form reloads without the typed passwords');
  await page.screenshot({ path: '/tmp/profile.png', fullPage: true });
  await openGroup('基础资料', nameField);
  await page.getByLabel('姓名', { exact: true }).fill('Discarded');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('input[name="name"]')?.value === 'Renamed Admin');
  assert.equal(await page.getByLabel('姓名', { exact: true }).inputValue(), 'Renamed Admin', 'cancel discards unsaved edits');
  await page.goto(`${origin}${entryPath}`);
  // The workspace switcher is its own header menu, separate from the account menu.
  await page.getByRole('button', { name: '切换空间', exact: true }).click();
  assert.match(await page.getByRole('menuitemradio').filter({ hasText: 'First workspace' }).textContent(), /拥有者（我创建的）/, 'workspace menu shows the role in each workspace');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: /Renamed Admin/ }).click();
  await page.getByRole('menuitem', { name: '个人资料', exact: true }).click();
  await nameField.waitFor();
  assert.equal(new URL(page.url()).pathname, '/zh-CN/account', 'workspace account menu opens the profile');
  await page.reload();
  await openGroup('账号安全', emailField);
  assert.equal(await page.getByRole('textbox', { name: '登录邮箱', exact: true }).inputValue(), 'renamed@example.invalid', '/account opens directly');
  await page.getByRole('button', { name: '返回', exact: true }).click();
  await page.waitForURL(url => url.pathname !== '/zh-CN/account');
  const fresh = await browser.newContext({ locale: 'zh-CN', extraHTTPHeaders: { 'Accept-Language': 'zh-CN' } });
  const visitor = await fresh.newPage();
  await visitor.goto(origin);
  await visitor.getByRole('button', { name: '登录', exact: true }).waitFor();
  assert.equal(await visitor.getByText('还没有账号？注册').count(), 0, 'closed registration hidden');
  assert(!requests.some(url => url.includes(token)), 'no HTTP URL contains setup token');
  assert(!(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).includes(token), 'setup proof never stored');
  assert.deepEqual(errors, []);
  console.log('PASS: web/manual proof, native fragment, password confirmation, setup/session, platform lists, workspace creation/entry, registration setting, own profile (name, email with current password, menus, direct URL), my role per workspace, no secret persistence, no browser errors');
} catch (error) {
  await globalThis.failurePage?.screenshot({ path: join(process.env.TEST_SCREENSHOT_DIR || tmpdir(), 'platform-ui-failure.png'), fullPage: true }).catch(() => {});
  throw error;
} finally {
  if (browser) await browser.close();
  if (server.exitCode === null) { server.kill('SIGTERM'); await new Promise(r => server.once('exit', r)); }
  await log.close();
  await rm(work, { recursive: true, force: true });
}
